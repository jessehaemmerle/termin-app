import { chromium } from '@playwright/test'
const S = process.argv[2]
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const errors = []
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
page.on('pageerror', (e) => errors.push(e.message))
await page.goto('http://mayer.localhost:3000/buchen')
await page.screenshot({ path: `${S}/b1.png`, fullPage: true })
await page.getByRole('link', { name: /Herrenhaarschnitt/ }).click()
await page.waitForURL(/leistung=/)
await page.screenshot({ path: `${S}/b2.png`, fullPage: true })
await page.getByRole('link', { name: /Keine Präferenz/ }).click()
await page.waitForURL(/person=any/)
await page.screenshot({ path: `${S}/b3.png`, fullPage: true })
await page.getByRole('link', { name: /Uhr wählen/ }).first().click()
await page.waitForURL(/zeit=/)
await page.getByLabel('Name').fill('Maria Muster')
await page.getByLabel('E-Mail-Adresse').fill('maria@example.com')
await page.getByLabel(/Mobilnummer/).fill('0664 1234567')
await page.waitForTimeout(2100)
await page.screenshot({ path: `${S}/b4.png`, fullPage: true })
await page.getByRole('button', { name: /Termin verbindlich buchen/ }).click()
await page.waitForURL(/\/termin\//, { timeout: 15000 })
await page.screenshot({ path: `${S}/b5.png`, fullPage: true })
console.log('URL', page.url())
if (errors.length) console.log('Fehler:\n' + errors.join('\n'))
await browser.close()
